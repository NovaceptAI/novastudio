function source(
  id: string,
  label: string,
  url: string,
  type: ApprovedSource['type'],
  credibility: ApprovedSource['credibility'],
  addedOn: string,
  notes?: string,
): ApprovedSource {
  return { id, label, url, type, credibility, addedOn, notes };
}

function voice(
  id: string,
  name: string,
  role: VoiceProfile['role'],
  language: VoiceProfile['language'],
  characteristics: string,
): VoiceProfile {
  return {
    id,
    name,
    role,
    language,
    characteristics,
    provider: 'unassigned',
    providerVoiceId: null,
    status: 'placeholder',
  };
}

